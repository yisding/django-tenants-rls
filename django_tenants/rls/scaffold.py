def _unique_source_kind(model, fields):
    """How the UNIQUE over ``fields`` was declared on ``model``.

    Returns ``(kind, name)`` -- ``kind`` is ``"constraint"`` |
    ``"unique_together"`` | ``"field"``; ``name`` is the constraint name for a
    ``Meta.constraints`` ``UniqueConstraint`` (else None). Mirrors
    :func:`checks._unique_fieldsets` so the generated removal operation matches the
    source declaration (a ``RemoveConstraint`` does **not** remove a field-level
    ``unique=True`` or a ``unique_together`` group).
    """
    from django.db.models import UniqueConstraint

    meta = model._meta
    fields_t = tuple(fields)
    for constraint in getattr(meta, "constraints", None) or ():
        if (isinstance(constraint, UniqueConstraint) and constraint.fields
                and tuple(constraint.fields) == fields_t):
            return "constraint", (constraint.name or None)
    unique_together = meta.unique_together or ()
    if unique_together and isinstance(unique_together[0], str):
        unique_together = (unique_together,)
    for group in unique_together:
        if tuple(group) == fields_t:
            return "unique_together", None
    if len(fields_t) == 1:
        try:
            f = meta.get_field(fields_t[0])
            if getattr(f, "unique", False) and not getattr(f, "primary_key", False):
                return "field", None
        except Exception:
            pass
    return "constraint", None


def _render_field_without_unique(model, field_name):
    """Render ``model.field_name`` as migration source with ``unique`` stripped.

    Uses Django's own migration serializer so the field's REAL type and options
    are reproduced (max_length, choices, etc.) instead of a hardcoded placeholder
    that would silently change the column. Best-effort: if the field cannot be
    reconstructed (exotic custom field, import failure) it returns a clearly
    flagged placeholder so the scaffold never crashes.
    """
    fallback = (
        "models.CharField(max_length=255, unique=False)"
        "  # TODO: could not introspect -- replace with your real field"
    )
    try:
        from django.db.migrations.writer import MigrationWriter
        from django.utils.module_loading import import_string

        field = model._meta.get_field(field_name)
        _name, path, args, kwargs = field.deconstruct()
        # unique defaults to False, so dropping it makes the field non-unique.
        kwargs.pop("unique", None)
        field_cls = import_string(path)
        rebuilt = field_cls(*args, **kwargs)
        src, _imports = MigrationWriter.serialize(rebuilt)
        return src
    except Exception:
        return fallback


def _unique_removal_op(model, fields):
    """Return the migration-operation text to drop the old tenant-blind UNIQUE.

    The operation TYPE matches how the UNIQUE was declared (see
    :func:`_unique_source_kind`): ``RemoveConstraint`` for a Meta
    ``UniqueConstraint``, ``AlterUniqueTogether`` for a ``unique_together`` group,
    ``AlterField`` for a field-level ``unique=True``. Field-specific parts are
    left as TODOs (the scaffold cannot reproduce the original field type or your
    full remaining ``unique_together`` set). The returned text is already indented
    to slot into the migration's ``operations`` list.
    """
    model_name = model._meta.model_name
    kind, cname = _unique_source_kind(model, fields)
    fields_t = tuple(fields)
    if kind == "unique_together":
        return (
            "        # Old UNIQUE is a Meta.unique_together group. AlterUniqueTogether\n"
            "        # REPLACES the whole set, so list your REMAINING groups (drop only\n"
            "        # %r); use set() if it was your only group.\n"
            "        migrations.AlterUniqueTogether(\n"
            '            name="%s",\n'
            "            unique_together=set(),  # TODO: your other unique_together groups\n"
            "        )," % (fields_t, model_name)
        )
    if kind == "field":
        fld = fields_t[0] if fields_t else "<field>"
        field_src = _render_field_without_unique(model, fld)
        return (
            "        # Old UNIQUE is a field-level unique=True. The field below is\n"
            "        # reconstructed from your model with unique dropped; review it\n"
            "        # (and add any custom-field import the scaffold could not infer).\n"
            "        migrations.AlterField(\n"
            '            model_name="%s",\n'
            '            name="%s",\n'
            "            field=%s,\n"
            "        )," % (model_name, fld, field_src)
        )
    name = cname or "<old_constraint_name>"
    todo = "" if cname else (
        "        # TODO: replace <old_constraint_name> with the real constraint name.\n"
    )
    return (
        "        # Old UNIQUE is a Meta.constraints UniqueConstraint.\n"
        "%s"
        "        migrations.RemoveConstraint(\n"
        '            model_name="%s",\n'
        '            name="%s",\n'
        "        )," % (todo, model_name, name)
    )


def unique_constraint_migration(model, fields):
    """Return migration text making a UNIQUE constraint tenant-scoped (Step 8).

    PostgreSQL checks UNIQUE constraints with RLS bypassed, so a UNIQUE that omits
    the tenant enforces uniqueness across ALL tenants and leaks cross-tenant row
    existence (check W005). This emits an ``AddConstraint`` of a new
    ``UniqueConstraint`` spanning ``[tenant_field, *fields]`` and a
    ``RemoveConstraint`` of the old, tenant-blind constraint.

    ``fields`` is the offending field set (the tuple from
    ``checks._unique_fieldsets``); the tenant field is prepended (and not
    duplicated if already present). The names of the new and old constraints are
    derived deterministically but flagged as TODOs because the old name depends on
    how the original constraint was declared (a ``unique_together`` /
    ``unique=True`` has an auto-generated name you must look up).
    """
    from . import conf

    app_label, model_name, object_name, db_table, label = _model_idents(model)
    tenant = conf.tenant_field()

    field_list = list(fields)
    # Prepend the tenant field, never duplicating it if the caller already has it.
    scoped = [tenant] + [f for f in field_list if f != tenant]

    scoped_repr = ", ".join(repr(f) for f in scoped)
    suffix = "_".join(field_list) if field_list else "unique"
    new_name = "%s_%s_per_tenant_uniq" % (db_table, suffix)
    # Postgres identifiers cap at 63 bytes; keep the generated name short enough.
    new_name = new_name[:63]

    # The drop operation must match how the old UNIQUE was declared.
    removal_op = _unique_removal_op(model, field_list)

    return '''\
"""Make the UNIQUE on {label} tenant-scoped (RLS migration Step 8).

Generated by ``manage.py rls_doctor --generate``. Review, then drop into
``{app_label}/migrations/`` and renumber to follow your latest migration.

PostgreSQL checks UNIQUE constraints with RLS BYPASSED, so the existing UNIQUE on
{fields!r} enforces uniqueness across ALL tenants and leaks cross-tenant row
existence. This migration replaces it with a tenant-scoped UniqueConstraint over
{scoped!r}.

TODO: also update the model's Meta so makemigrations agrees with this state:
remove the old unique=True / unique_together / UniqueConstraint and add
``models.UniqueConstraint(fields=[{scoped_repr}], name="{new_name}")``.
"""

from django.db import migrations, models


class Migration(migrations.Migration):

    # TODO: set this to your app's latest migration.
    dependencies = [
        # ("{app_label}", "<previous_migration>"),
    ]

    operations = [
        # Add the tenant-scoped UNIQUE first so uniqueness is never unenforced.
        migrations.AddConstraint(
            model_name="{model_name}",
            constraint=models.UniqueConstraint(
                fields=[{scoped_repr}],
                name="{new_name}",
            ),
        ),
        # Then drop the old, tenant-blind UNIQUE -- with the operation that
        # matches how it was declared (RemoveConstraint / AlterUniqueTogether /
        # AlterField), since a RemoveConstraint cannot remove a field-level
        # unique=True or a unique_together group:
{removal_op}
    ]
'''.format(
        label=label,
        app_label=app_label,
        model_name=model_name,
        fields=tuple(field_list),
        scoped=tuple(scoped),
        scoped_repr=scoped_repr,
        new_name=new_name,
        removal_op=removal_op,
    )

def _model_idents(model):
    """Return the identifiers a migration/DDL needs from a model.

    Returns ``(app_label, model_name, object_name, db_table, label)``. Kept in
    one place so every generator references the model's ``_meta`` consistently.
    """
    meta = model._meta
    return (
        meta.app_label,
        meta.model_name,
        meta.object_name,
        meta.db_table,
        meta.label,
    )



"""Migration / SQL scaffold generators for the RLS migration assistant.

These four generators turn a concrete :class:`~django_tenants.rls.models.TenantRLSModel`
(or, for third-party tables, a bare table name) into ready-to-edit text a human
can drop into an app's ``migrations/`` directory or run with ``psql``. They are
the "GENERATE" tier of the assistant (``manage.py rls_doctor --generate``): they
return strings only and **write nothing**, leaving placement and review to the
operator.

Each generator composes the existing primitives rather than re-deriving the DDL:

* :func:`enable_rls_migration` emits a migration using
  :class:`~django_tenants.rls.operations.EnableRLS` +
  :class:`~django_tenants.rls.operations.CreateTenantPolicy` (Step 6).
* :func:`staged_fk_migration` emits the staged tenant-FK migration text for
  Step 3/5: ``AddField`` with ``null=True``, a commented ``RunPython`` backfill
  STUB (Step 4 is app-specific and DANGEROUS -- never auto-generated runnable),
  and a clearly-delimited ``AlterField`` to ``null=False`` gated on the backfill
  having completed (Step 5).
* :func:`third_party_policy_sql` emits raw ENABLE/FORCE + CREATE POLICY DDL for a
  table you cannot subclass (e.g. ``authtoken_token``), Step 7. Its USING /
  WITH CHECK clauses come straight from
  :meth:`~django_tenants.rls.policies.TenantPolicy.get_using_expression` /
  :meth:`~django_tenants.rls.policies.TenantPolicy.get_check_expression` so the
  DDL is byte-identical to what the framework's schema editor would emit. It emits
  the *policy* only and assumes the tenant column already exists.
* :func:`isolate_external_table_sql` emits the FULL ordered prerequisite sequence
  for such a table -- ADD COLUMN with a GUC-reading DEFAULT + tenant FK, a backfill
  STUB, an optional ``SET NOT NULL``, UNIQUE rewrites, then the policy -- and points
  at :class:`~django_tenants.rls.operations.IsolateExternalTable`, the reversible
  migration operation that performs the same sequence.
* :func:`unique_constraint_migration` emits ``AddConstraint`` of a
  tenant-scoped ``UniqueConstraint`` + ``RemoveConstraint`` of the old one
  (Step 8).

All Django imports are lazy (inside the functions) so importing this module stays
cheap and free of app-registry side effects, matching the rest of this package.
"""

# ``_quote_ident`` lives in operations.py (its canonical home -- the reversible
